/* =========================================================
   KOSI — минимальный service worker.
   Нужен только для того, чтобы браузер предлагал
   «Установить приложение» / «Добавить на экран Домой».
   Ничего не кэширует агрессивно, просто пропускает запросы дальше.
   ========================================================= */

self.addEventListener('install', (event) => {
  self.skipWaiting();
});

self.addEventListener('activate', (event) => {
  self.clients.claim();
});

self.addEventListener('fetch', (event) => {
  // Просто отдаём обычный сетевой запрос.
  // Оставлен пустой обработчик — он обязателен, чтобы сайт
  // считался «устанавливаемым приложением» (PWA) в Chrome/Android.
  event.respondWith(fetch(event.request));
});
